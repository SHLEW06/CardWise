#!/usr/bin/env node
/* npm run extension:calibrations
   Copies connector/calibration/<bank>.json (the one source of truth) into
   extension/lib/calibrations.js, keeping only what the extension uses.
   A test fails when the two drift apart. */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const BANK_IDS = ["amex", "chase", "mockbank"];

export function readCalibrations(root = ROOT) {
  const out = {};
  for (const id of BANK_IDS) {
    const p = resolve(root, "connector/calibration", `${id}.json`);
    if (!existsSync(p)) { out[id] = null; continue; }
    const c = JSON.parse(readFileSync(p, "utf8"));
    out[id] = { offers: c.offers, add: c.add ?? null };
  }
  return out;
}

export function render(cals) {
  return `/* GENERATED by extension/scripts/sync-calibrations.mjs from
   connector/calibration/*.json — do not edit; run \`npm run extension:calibrations\`.
   null = not calibrated yet (the extension says so on that bank's page). */
export const CALIBRATIONS = ${JSON.stringify(cals, null, 2)};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const cals = readCalibrations();
  writeFileSync(resolve(ROOT, "extension/lib/calibrations.js"), render(cals));
  console.log(`extension/lib/calibrations.js: ${Object.entries(cals).map(([k, v]) => `${k} ${v ? "✓" : "—"}`).join(", ")}`);
}
