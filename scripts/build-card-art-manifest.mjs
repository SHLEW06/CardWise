#!/usr/bin/env node
/* ============================================================================
   scripts/build-card-art-manifest.mjs
   ----------------------------------------------------------------------------
   Scans public/cards/ for real card faces named after a catalog card id and
   writes src/data/cardArtManifest.js. The schema layer reads that manifest, so
   dropping `public/cards/amex-gold.png` into the folder is all it takes for the
   real art to show up everywhere CardArt renders.

   Usage:
     node scripts/build-card-art-manifest.mjs            # write manifest
     node scripts/build-card-art-manifest.mjs --missing  # list cards w/o art

   Runs automatically via `predev` / `prebuild` npm hooks.
   ========================================================================== */

import { readdirSync, writeFileSync, existsSync, mkdirSync, readFileSync } from "node:fs";
import { resolve, dirname, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const CARDS_DIR = resolve(ROOT, "public/cards");
const BACKGROUNDS_DIR = resolve(ROOT, "public/backgrounds");
/* v6 §18 Backdrop slots; a photo public/backgrounds/<slot>.avif|webp wins over
   the procedural scene. */
export const BACKDROP_SLOTS = ["home", "checkout", "offers", "lab", "explore", "survey", "card", "profile"];
/* v7 §9.11 focal images: public/backgrounds/focal-<slot>.avif|webp|jpg|png
   (one art-directed photo or render per hero; CSS/SVG stand-in until then). */
export const isFocalSlot = (slot) => /^focal-[a-z0-9-]+$/.test(slot);
const BG_RANK = { ".avif": 0, ".webp": 1, ".jpg": 2, ".png": 3 };

export function scanBackgrounds(dir = BACKGROUNDS_DIR) {
  if (!existsSync(dir)) return {};
  const out = {};
  for (const file of readdirSync(dir)) {
    const ext = extname(file).toLowerCase();
    const slot = basename(file, extname(file)).toLowerCase();
    if (!(ext in BG_RANK) || !(BACKDROP_SLOTS.includes(slot) || isFocalSlot(slot))) continue;
    if (!out[slot] || BG_RANK[ext] < BG_RANK[extname(out[slot])]) out[slot] = `/backgrounds/${file}`;
  }
  return out;
}
const OUT_FILE = resolve(ROOT, "src/data/cardArtManifest.js");

/* Preference order when the same id has several files. */
const EXT_RANK = { ".webp": 0, ".png": 1, ".jpg": 2, ".jpeg": 3, ".svg": 4 };

export function scanCardArt(dir = CARDS_DIR) {
  if (!existsSync(dir)) return {};
  const found = {};
  for (const file of readdirSync(dir)) {
    const ext = extname(file).toLowerCase();
    if (!(ext in EXT_RANK)) continue;
    const id = basename(file, extname(file)).toLowerCase();
    const prev = found[id];
    if (!prev || EXT_RANK[ext] < EXT_RANK[extname(prev).toLowerCase()]) {
      found[id] = file;
    }
  }
  const manifest = {};
  for (const id of Object.keys(found).sort()) manifest[id] = `/cards/${found[id]}`;
  return manifest;
}

export function renderManifest(manifest, backgrounds = {}) {
  const entries = Object.entries(manifest)
    .map(([id, url]) => `  ${JSON.stringify(id)}: ${JSON.stringify(url)},`)
    .join("\n");
  return `/* AUTO-GENERATED by scripts/build-card-art-manifest.mjs — do not edit.
   Drop <card-id>.png|webp|jpg|svg into public/cards/ and re-run \`npm run art\`.
   ${Object.keys(manifest).length} card face(s) found. */
export const CARD_ART_MANIFEST = {
${entries}
};
export default CARD_ART_MANIFEST;

/* Photo backdrops found in public/backgrounds/ (v6 §18). */
export const BACKGROUND_MANIFEST = ${JSON.stringify(backgrounds)};
`;
}

function writeManifest() {
  const manifest = scanCardArt();
  if (!existsSync(dirname(OUT_FILE))) mkdirSync(dirname(OUT_FILE), { recursive: true });
  const next = renderManifest(manifest, scanBackgrounds());
  const prev = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : null;
  if (prev !== next) writeFileSync(OUT_FILE, next);
  return manifest;
}

async function reportMissing(manifest) {
  /* Import the catalog lazily — it's ESM and pulls in the schema. */
  const { CARDS } = await import(resolve(ROOT, "src/data/cards/index.js"));
  const byIssuer = {};
  let have = 0;
  for (const c of CARDS) {
    if (manifest[c.id]) { have += 1; continue; }
    (byIssuer[c.issuer] ||= []).push(c);
  }
  console.log(`\nCard art: ${have}/${CARDS.length} cards have a real image.\n`);
  if (have === CARDS.length) return;
  console.log("Missing — name the file exactly <id>.png (or .webp/.jpg) in public/cards/:\n");
  for (const issuer of Object.keys(byIssuer).sort()) {
    console.log(`  ${issuer}`);
    for (const c of byIssuer[issuer]) console.log(`    ${c.id.padEnd(28)} ${c.name}`);
  }
  console.log("");
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const manifest = writeManifest();
  if (process.argv.includes("--missing")) {
    await reportMissing(manifest);
  } else {
    console.log(`card-art manifest: ${Object.keys(manifest).length} image(s) → src/data/cardArtManifest.js`);
  }
}
