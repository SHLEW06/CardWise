#!/usr/bin/env node
/* v7e Part 3.2: docs/data/premium_hotel_prices.csv → src/data/premiumHotels.generated.json
   `npm run hotels`. Source and date: docs/THIRD_PARTY.md.
   Realistic nightly rate = the average where the source has one, otherwise
   lowest × 1.25 — never the lowest alone (it's a best-date figure). */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CSV = resolve(ROOT, "docs/data/premium_hotel_prices.csv");
const OUT = resolve(ROOT, "src/data/premiumHotels.generated.json");

/* CSV city → the survey's destination keys (src/data/routes.js). Milan has no
   destination of its own; it's kept as a city in Italy. */
const CITY_KEY = { Shanghai: "shanghai", Seoul: "seoul", Tokyo: "tokyo", "Hong Kong": "hongkong", London: "london", Paris: "paris", Rome: "rome", Milan: "milan", Singapore: "singapore", Honolulu: "hawaii" };
const PROGRAM = { "Chase Edit": "edit", "Amex THC": "thc", "Amex FHR": "fhr" };
export const LOWEST_UPLIFT = 1.25;

function parse(text) {
  const [head, ...rows] = text.trim().split(/\r?\n/);
  const keys = head.split(",");
  return rows.map((line) => {
    const cells = line.split(",");
    return Object.fromEntries(keys.map((k, i) => [k, cells[i] ?? ""]));
  });
}

const rows = parse(readFileSync(CSV, "utf8"));
const cities = {};
const sources = new Set();
let checked = "";
for (const r of rows) {
  const key = CITY_KEY[r.city];
  const program = PROGRAM[r.program];
  if (!key || !program) { console.warn("skipped", r.city, r.program); continue; }
  const lowest = Number(r.lowest_nightly_usd);
  const avg = r.avg_nightly_usd ? Number(r.avg_nightly_usd) : null;
  const rate = avg ?? Math.round(lowest * LOWEST_UPLIFT);
  (cities[key] ||= { name: r.city, country: r.country, hotels: [] }).hotels.push({
    program, hotel: r.hotel, lowest, avg, rate, rateBasis: avg ? "average" : "lowest × 1.25", minNights: Number(r.min_nights) || 1, source: r.source, checked: r.checked,
  });
  sources.add(r.source);
  if (r.checked > checked) checked = r.checked;
}
for (const c of Object.values(cities)) c.hotels.sort((a, b) => a.rate - b.rate);
const out = { generatedFrom: "docs/data/premium_hotel_prices.csv", checked, sources: [...sources], cities };
writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");
/* The same data as an ES module, so plain Node (golden report) and Vite both
   import it without JSON import attributes. */
writeFileSync(OUT.replace(/\.json$/, ".js"), `/* AUTO-GENERATED by scripts/build-premium-hotels.mjs from ${out.generatedFrom} — do not edit. */\nexport const PREMIUM_HOTELS = ${JSON.stringify(out, null, 2)};\nexport default PREMIUM_HOTELS;\n`);
console.log(`wrote ${OUT}: ${rows.length} hotels in ${Object.keys(cities).length} cities`);
