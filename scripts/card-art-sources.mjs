#!/usr/bin/env node
/* Writes docs/CARD_ART_SOURCES.md: where every issuer photo in public/cards/
   came from (v7: "keep issuer photos for now, record each image's source
   URL"). Reads public/cards/art-urls.txt (local, gitignored, written when
   the art was fetched) and the files actually present. The doc is committed;
   the images are not. Run `npm run art:sources` after adding art. */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, extname, basename } from "node:path";

const ROOT = process.cwd();
const DIR = resolve(ROOT, "public/cards");
const LIST = resolve(DIR, "art-urls.txt");
const OUT = resolve(ROOT, "docs/CARD_ART_SOURCES.md");
const IMG = new Set([".png", ".webp", ".jpg", ".jpeg", ".svg"]);

const files = existsSync(DIR) ? readdirSync(DIR).filter((f) => IMG.has(extname(f).toLowerCase())) : [];
const urls = {};
let collected = "";
if (existsSync(LIST)) {
  for (const line of readFileSync(LIST, "utf8").split("\n")) {
    const m = /^#.*collected (\d{4}-\d{2}-\d{2})/.exec(line);
    if (m) collected = m[1];
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const [id, url] = t.split(/\s+/);
    if (id && url) urls[id.toLowerCase()] = url;
  }
}
const rows = files.map((f) => ({ id: basename(f, extname(f)).toLowerCase(), file: f })).sort((a, b) => a.id.localeCompare(b.id));
const missing = rows.filter((r) => !urls[r.id]);
const md = [
  "# Card art sources",
  "",
  "Generated by `npm run art:sources` from `public/cards/art-urls.txt`. The",
  "images themselves are issuer property, kept local (gitignored) for personal",
  "use; the public launch switches to our rendered faces (REDESIGN_SPEC §9.11,",
  "Profile → Card pictures).",
  "",
  `Photos: ${rows.length} · with a recorded source: ${rows.length - missing.length} · collected ${collected || "date not recorded"}.`,
  "",
  missing.length ? `**No source recorded:** ${missing.map((r) => `\`${r.id}\``).join(", ")} — re-fetch from the issuer page or add the URL to art-urls.txt.` : "Every photo has a recorded source.",
  "",
  "| Card id | File | Source URL |",
  "|---|---|---|",
  ...rows.map((r) => `| \`${r.id}\` | ${r.file} | ${urls[r.id] ? urls[r.id] : "— not recorded —"} |`),
  "",
].join("\n");
writeFileSync(OUT, md);
console.log(`docs/CARD_ART_SOURCES.md: ${rows.length} photos, ${missing.length} without a source`);
