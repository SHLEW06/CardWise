#!/usr/bin/env node
/* v7c Part 6: writes the audit table in docs/CARD_AUDIT.md (between the
   v7c markers) from src/data/cardAudit.js — card · fields changed ·
   unverified items · source · date. `npm run audit:v7c`. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { AUDIT } from "../src/data/cardAudit.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DOC = resolve(ROOT, "docs/CARD_AUDIT.md");
const START = "<!-- v7c-audit:start -->";
const END = "<!-- v7c-audit:end -->";
const esc = (s) => String(s).replace(/\|/g, "\\|");
const host = (u) => { try { return new URL(u).hostname.replace(/^www\./, ""); } catch { return u; } };

const rows = Object.entries(AUDIT).sort((a, b) => a[1].group - b[1].group || a[1].batch - b[1].batch || (a[0] < b[0] ? -1 : 1));
const groups = { 1: "Group 1 · the owner's cards", 2: "Group 2 · recommended to the owner's profile", 3: "Group 3 · the 40 most popular", 4: "Group 4 · everything else" };
let out = `${START}\n_Generated by \`npm run audit:v7c\` from \`src/data/cardAudit.js\`. Every credit on an audited card carries the issuer's own sentence there._\n`;
for (const g of [1, 2, 3, 4]) {
  const rs = rows.filter(([, a]) => a.group === g);
  if (!rs.length) continue;
  out += `\n### ${groups[g]}\n\n| Card | Fields changed | Unverified (counted $0) | Source | Date |\n|---|---|---|---|---|\n`;
  for (const [id, a] of rs) {
    out += `| \`${id}\` (batch ${a.batch}) | ${a.changed.length ? a.changed.map(esc).join("<br>") : "No change — matches the page"} | ${a.unverified.length ? a.unverified.map((u) => esc(u.what)).join("<br>") : "—"} | [${host(a.source)}](${a.source}) | ${a.checked} |\n`;
  }
}
out += `\n${END}`;

let doc = readFileSync(DOC, "utf8");
if (doc.includes(START)) doc = doc.replace(new RegExp(`${START}[\\s\\S]*?${END}`), out);
else doc = doc.replace(/^(# Card audit[^\n]*\n)/, `$1\n## v7c full audit (2026-11-22, in progress)\n\nRead on each issuer's own page (rendered in Chrome, so JavaScript-only Amex pages show their terms). Rules: blogs only point at things to check; anything the page doesn't confirm is marked unverified and counted $0. Order: the owner's cards, then every card the optimizer recommends to the owner's profile, then the 40 most popular, then the rest — batches of about 10. **Stopped after groups 1 and 2 for the owner's review.**\n\n${out}\n\n`);
writeFileSync(DOC, doc);
console.log(`wrote ${rows.length} audited cards to docs/CARD_AUDIT.md`);
