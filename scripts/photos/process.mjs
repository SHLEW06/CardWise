// Crops each cached original to 3:2 around its focal point and writes sharp
// WebP files: public/photos/<id>.webp (1200x800, q~72) and <id>-sm.webp (600x400).
// Needs ffmpeg and cwebp. Run after scripts/photos/fetch.mjs.
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const sources = JSON.parse(fs.readFileSync(path.join(root, "scripts/photos/sources.json"), "utf8"));
const outDir = path.join(root, "public/photos");
fs.mkdirSync(outDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "cw-photos-"));
const MAX = 140 * 1024;

for (const s of sources) {
  const src = path.join(root, s.cached);
  const [fx, fy] = s.focus || [0.5, 0.5];
  for (const [w, h, suffix] of [[1200, 800, ""], [600, 400, "-sm"]]) {
    const png = path.join(tmp, s.id + suffix + ".png");
    /* crop 3:2 (largest that fits), centred on the focal point, then Lanczos down-scale */
    const crop = `crop='if(gt(iw/ih,3/2),ih*3/2,iw)':'if(gt(iw/ih,3/2),ih,iw*2/3)':'clip((iw-out_w)*${fx},0,iw-out_w)':'clip((ih-out_h)*${fy},0,ih-out_h)',scale=${w}:${h}:flags=lanczos`;
    execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-i", src, "-vf", crop, "-frames:v", "1", png]);
    const dest = path.join(outDir, s.id + suffix + ".webp");
    let q = suffix ? 74 : 74;
    for (; q >= 50; q -= 4) {
      execFileSync("cwebp", ["-quiet", "-q", String(q), "-m", "6", "-sharp_yuv", "-f", "20", png, "-o", dest]);
      if (suffix || fs.statSync(dest).size <= MAX) break;
    }
    console.log(s.id + suffix, w + "x" + h, "q" + q, Math.round(fs.statSync(dest).size / 1024) + " KB");
  }
}
fs.rmSync(tmp, { recursive: true, force: true });

/* manifest for the app: src/data/photos.js */
const sizeOf = (f) => fs.statSync(path.join(outDir, f)).size;
const entries = sources.map((s) => ({
  id: s.id, place: s.place, src: `/photos/${s.id}.webp`, srcSmall: `/photos/${s.id}-sm.webp`, width: 1200, height: 800, widthSmall: 600,
  alt: s.alt, credit: s.author, license: s.license, sourceUrl: s.sourceUrl,
}));
fs.writeFileSync(path.join(root, "src/data/photos.js"),
`/* Editorial photos (Wikimedia Commons, CC0 / public domain only). Generated by
   scripts/photos/process.mjs from scripts/photos/sources.json; see docs/THIRD_PARTY.md. */
export const PHOTOS = ${JSON.stringify(entries, null, 2)};

export const PHOTO_BY_ID = Object.fromEntries(PHOTOS.map((p) => [p.id, p]));
export const photo = (id) => PHOTO_BY_ID[id];
export const photos = (ids) => ids.map((id) => PHOTO_BY_ID[id]).filter(Boolean);

/* Themed sets used by PhotoBand across the app. */
export const PHOTO_SETS = {
  destinations: ["positano", "kyoto-gion", "maldives-pool", "paris-dusk"],
  hotels: ["pool-hoshinoya", "maldives-pool", "positano", "alps-hut"],
  strategies: ["amalfi-sunset"],
  explore: ["paris-dusk", "pool-palms", "twa-lounge", "nyc-harbor"],
  lab: ["maldives-blue", "alps-hut", "nyc-midtown"],
};

/* Card Detail: pick a themed image from the card's tags / currency (no new card data). */
const pick = (list, key) => list[[...String(key)].reduce((a, c) => a + c.charCodeAt(0), 0) % list.length];
export function photoForCard(card) {
  if (!card) return PHOTO_BY_ID["nyc-harbor"];
  const tags = card.tags || [];
  const cur = String(card.currency || "");
  if (tags.includes("lounge")) return PHOTO_BY_ID["twa-lounge"];
  if (tags.includes("hotel") || /bonvoy|hilton|ihg|hyatt|marriott/i.test(cur)) return PHOTO_BY_ID[pick(["pool-hoshinoya", "pool-palms", "maldives-pool"], card.id)];
  if (tags.includes("airline") || /skymiles|mileageplus|aadvantage|miles/i.test(cur)) return PHOTO_BY_ID[pick(["amalfi-sunset", "alps-hut", "maldives-blue"], card.id)];
  if ((tags.includes("food") || tags.includes("dining")) && !tags.includes("travel")) return PHOTO_BY_ID["dinner-candle"];
  if (tags.includes("travel") || tags.includes("premium") || tags.includes("luxury")) return PHOTO_BY_ID[pick(["positano", "paris-dusk", "kyoto-gion", "amalfi-sunset", "alps-hut", "maldives-blue"], card.id)];
  if (tags.includes("cashback") || /cash/i.test(cur)) return PHOTO_BY_ID[pick(["nyc-midtown", "nyc-harbor"], card.id)];
  if (tags.includes("business")) return PHOTO_BY_ID["nyc-harbor"];
  return PHOTO_BY_ID[pick(["nyc-harbor", "paris-dusk"], card.id)];
}
`);
console.log("wrote src/data/photos.js");
