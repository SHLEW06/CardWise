// @vitest-environment jsdom
/* v7c Part 3 — trips replace the airport steps; route data from US DOT BTS
   T-100 Segment (all carriers); airlines per route. */
import React from "react";
import { describe, it, expect, afterEach, beforeEach } from "vitest";
import { render, screen, fireEvent, cleanup, within } from "@testing-library/react";
import "@testing-library/jest-dom/vitest";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import Survey from "../components/v5/survey/Survey.jsx";
import { saveV5Profile, loadV5Profile } from "../state/v5Profile.js";
import { normalizeProfile } from "../engine/profileDefaults.js";
import DATA from "../data/routes.generated.json";
import {
  inferTrips, routeOptions, nonstopCarriers, searchPlaces, suggestRoutes, rowsFromAirports, isIntl, placeAirports,
  ROUTE_DATA_SOURCE, GOOD_NONSTOP, CARRIER_INFO,
} from "../engine/v5/tripRoutes.js";

afterEach(cleanup);
beforeEach(() => localStorage.clear());
const cont = () => fireEvent.click(screen.getByRole("button", { name: /Continue|Save/ }));
const OWNER = [
  { from: "ATL", to: "us", trips: 3 }, { from: "ATL", to: "ICN", trips: 1 },
  { from: "NYC", to: "TPE", trips: 1 }, { from: "NYC", to: "c:Tokyo, Japan", trips: 1 }, { from: "BDL", to: "us", trips: 1 },
];

describe("3.5 · route data: BTS T-100 Segment, latest 12 months", () => {
  it("is generated by a build script, compact, and records its source and months", () => {
    expect(DATA.source).toMatch(/BTS, T-100 Segment \(All Carriers\)/);
    expect(DATA.months).toHaveLength(12);
    expect(ROUTE_DATA_SOURCE.months[11] >= "2026-01").toBe(true);
    expect(Object.keys(DATA.routes).length).toBeGreaterThan(500);
    expect(readFileSync(resolve(process.cwd(), "scripts/build-routes.mjs"), "utf8")).toMatch(/DL_SelectFields\.aspx\?gnoyr_VQ=FMG/);
    const third = readFileSync(resolve(process.cwd(), "docs/THIRD_PARTY.md"), "utf8");
    expect(third).toMatch(/T-100 Segment/);
    expect(third).toContain(DATA.months[0]);
    expect(third).toContain(DATA.months[11]);
    expect(third).toMatch(/OpenFlights is not used/);
  });
  it("departures are per carrier per airport pair (domestic and international)", () => {
    expect(DATA.routes.ATL.LAX.DL).toBeGreaterThan(3000);
    expect(DATA.routes.ATL.ICN.KE).toBeGreaterThan(GOOD_NONSTOP);
    /* Regional flights count for the airline they fly for (Endeavor → Delta). */
    expect(nonstopCarriers("BDL", "DTW")[0]).toMatchObject({ carrier: "DL" });
  });
});

describe("3.1–3.4 · trips step", () => {
  it("one row per trip: from (airport or metro) → to (city or airport), trips, cabin, work; domestic/international automatic", () => {
    saveV5Profile({});
    render(<Survey initialMode="quick" initialStepId="travel" initialProfile={loadV5Profile()} />);
    expect(screen.getByRole("heading", { level: 1 })).toHaveTextContent("Add the trips you take");
    fireEvent.change(screen.getByLabelText("From"), { target: { value: "nyc" } });
    fireEvent.click(screen.getByRole("option", { name: /New York \(JFK \/ LGA \/ EWR\)/ }));
    fireEvent.change(screen.getByLabelText("To"), { target: { value: "tokyo" } });
    fireEvent.click(screen.getByRole("option", { name: "Tokyo (HND / NRT)" }));
    fireEvent.click(screen.getByRole("button", { name: "Add trip" }));
    const row = screen.getByLabelText("Trips a year, NYC to Tokyo").closest("li");
    expect(within(row).getByText("International")).toBeInTheDocument();
    fireEvent.change(within(row).getByLabelText("Cabin, NYC to Tokyo"), { target: { value: "business" } });
    fireEvent.click(within(row).getByRole("button", { name: "I fly for work, NYC to Tokyo" }));
    /* Bags asked once, not per row. */
    expect(screen.getAllByRole("radiogroup", { name: "Checked bags per trip" })).toHaveLength(1);
    cont();
    const p = normalizeProfile(loadV5Profile());
    expect(p.travel.tripRows).toEqual([{ from: "NYC", to: "c:Tokyo, Japan", trips: 1, cabin: "business", work: true, airline: null, nights: null }]);
    expect(p.travel).toMatchObject({ trips: 1, homeAirport: "JFK", intlShare: 1, cabin: "business" });
  });
  it("one-tap suggestions of common routes from airports already entered", () => {
    saveV5Profile({ travel: { tripRows: [{ from: "ATL", to: "ICN", trips: 1 }] } });
    render(<Survey initialMode="quick" initialStepId="travel" initialProfile={loadV5Profile()} />);
    const ideas = screen.getByRole("group", { name: "Suggested routes" });
    const first = within(ideas).getAllByRole("button")[0];
    expect(first.textContent).toMatch(/^ATL → /);
    fireEvent.click(first);
    expect(screen.getAllByRole("listitem").filter((li) => li.classList.contains("trip-row"))).toHaveLength(2);
    expect(suggestRoutes(["ATL"], [], 3).map((r) => r.to)).toEqual(expect.arrayContaining(["MCO"]));
  });
  it("home airports, domestic/international split, airlines and programs come from the rows", () => {
    const p = normalizeProfile({ travel: { tripRows: OWNER } });
    expect(p.travel.airports.map((a) => a.code)).toEqual(["ATL", "NYC", "BDL"]);
    expect(p.travel.trips).toBe(7);
    expect(p.travel.intlShare).toBeCloseTo(3 / 7, 9);
    expect(p.travel.homeAirport).toBe("ATL");
    expect(p.brands.airlines).toEqual(expect.arrayContaining(["delta", "united"]));
    expect(isIntl("ICN") && !isIntl("us") && !isIntl("HNL")).toBe(true);
  });
});

describe("3.6–3.8 · airline inference", () => {
  it("ranks carriers by nonstop flights: ATL→LAX is Delta; ATL→Seoul is Delta and Korean Air (both Delta miles)", () => {
    const r = inferTrips([{ from: "ATL", to: "LAX", trips: 2 }, { from: "ATL", to: "ICN", trips: 1 }]);
    expect(r.routes[0].text).toBe("ATL→LAX: Delta (most flights)");
    expect(r.routes[1].text).toMatch(/^ATL→Seoul: Delta, Korean Air/);
    expect(r.byProgram).toEqual({ delta: 3 });
  });
  it("no good nonstop → the best one-stop through the home airport's airline and its alliance (EWR→Taipei: United, EVA)", () => {
    expect(nonstopCarriers("EWR", "TPE").filter((c) => c.departures >= GOOD_NONSTOP)).toEqual([]);
    const [o] = routeOptions({ from: "EWR", to: "TPE" });
    expect(o).toMatchObject({ program: "united", kind: "onestop" });
    expect(o.carriers[0]).toBe("United");
    expect(CARRIER_INFO[o.carrierCodes[1]].alliance).toBe("star");
    const r = inferTrips([{ from: "EWR", to: "TPE", trips: 1 }]);
    expect(r.routes[0].text).toMatch(/^EWR→Taipei: United, (EVA Air|.+) \(one stop, via [A-Z]{3}\)$/);
  });
  it("preferences only break close calls (NYC); they never override a clear winner", () => {
    const nyc = [{ from: "NYC", to: "us", trips: 2 }];
    expect(inferTrips(nyc).routes[0].pick.program).toBe("delta");                 // most flights from New York
    expect(inferTrips(nyc, ["united"]).routes[0].pick.program).toBe("united");    // close call: their pick
    const atl = [{ from: "ATL", to: "LAX", trips: 2 }];
    expect(inferTrips(atl, ["aa"]).routes[0].pick.program).toBe("delta");          // Delta flies it 10× more
  });
  it("an edited row keeps its airline", () => {
    const r = inferTrips([{ from: "NYC", to: "c:Tokyo, Japan", trips: 1, airline: "aa" }]);
    expect(r.routes[0].pick.program).toBe("aa");
    expect(r.routes[0].text).toMatch(/\(your pick\)$/);
  });
  it("the survey shows the result per route and lets them edit it", () => {
    saveV5Profile({ travel: { tripRows: [{ from: "NYC", to: "c:Tokyo, Japan", trips: 1 }] } });
    render(<Survey initialMode="quick" initialStepId="travel" initialProfile={loadV5Profile()} />);
    expect(within(screen.getByTestId("airlines-inferred")).getByText(/^NYC→Tokyo: /)).toBeInTheDocument();
    const menu = screen.getByLabelText("Airline, NYC to Tokyo");
    expect(menu).toHaveValue("");   // "Let CardWise pick"
    fireEvent.change(menu, { target: { value: "aa" } });
    cont();
    expect(normalizeProfile(loadV5Profile()).travel.tripsByAirline).toEqual({ aa: 1 });
  });
});

describe("migration", () => {
  it("v7b airports + destinations → rows; place search finds metros, cities and airports", () => {
    const rows = rowsFromAirports([{ code: "ATL", trips: 4, destinations: [{ key: "domestic", trips: 2 }, { key: "seoul", trips: 1 }] }, { code: "NYC", trips: 2, destinations: [{ key: "taipei", trips: 1 }, { key: "tokyo", trips: 1 }] }]);
    expect(rows.map((r) => `${r.from}>${r.to}:${r.trips}`)).toEqual(["ATL>ICN:1", "ATL>us:3", "NYC>TPE:1", "NYC>c:Tokyo, Japan:1"]);
    expect(searchPlaces("nyc")[0].key).toBe("NYC");
    expect(searchPlaces("tokyo")[0]).toMatchObject({ key: "c:Tokyo, Japan", airports: ["HND", "NRT"] });
    expect(placeAirports("NYC")).toEqual(["JFK", "LGA", "EWR"]);
  });
});
