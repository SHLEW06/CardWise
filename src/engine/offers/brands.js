/* ============================================================================
   engine/offers/brands.js — merchant/brand dictionary.
   ----------------------------------------------------------------------------
   Pure data. Every brand maps to a semantic purchase category from
   cardRouter.CATEGORY_RESOLVERS so base-earn math reuses the existing router.

   Shape:
     key        stable slug (what offers.brandKey points at)
     name       display
     category   semantic category for an in-store / default purchase
     online     category when bought online (defaults: category if it's a
                merchant-specific one like amazon/walmart, else "onlineShopping")
     aliases    other spellings / sub-brands / what shows on statements
     tags       "mall" (typical mall tenant), "outlet", "bigbox", "grocery", …
   ========================================================================== */

const MERCHANT_SPECIFIC = new Set(["amazon", "walmart", "target", "costco"]);

function b(key, name, category, aliases = [], opts = {}) {
  const online = opts.online
    || (MERCHANT_SPECIFIC.has(category) ? category : null)
    || (["groceries", "dining", "gas", "drugstores", "streaming", "flights", "hotels",
         "rentalCars", "transit", "rideshare", "utilities", "insurance", "tuition", "rent",
         "deltaFlight", "unitedFlight", "americanFlight", "southwestFlight",
         "marriott", "hyatt", "hilton", "ihg", "evCharging"].includes(category) ? category : "onlineShopping");
  return { key, name, category, online, aliases, tags: opts.tags || [], inStore: opts.inStore !== false };
}

